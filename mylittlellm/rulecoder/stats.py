"""Small-sample statistics for paired condition comparisons."""
import math


def wilson(successes, n, z=1.96):
    """Wilson score interval in percent; behaves sensibly near 0% and 100% unlike the normal interval."""
    if n == 0:
        return (0.0, 0.0)
    p = successes / n
    centre = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return (round(100 * (centre - half), 1), round(100 * (centre + half), 1))


def mcnemar_exact(wins, losses):
    """Two-sided exact binomial test on discordant pairs (tasks whose outcome changed)."""
    n, k = wins + losses, min(wins, losses)
    if n == 0:
        return 1.0
    return min(1.0, 2 * sum(math.comb(n, i) for i in range(k + 1)) / 2 ** n)
